export const getTeamLogo = (name: string): string | null => {
    const id = teamIdMap[name];
    if (id) {
        return `https://media.api-sports.io/football/teams/${id}.png`;
    }

    // Fallback heuristic for teams not in mapping
    return `https://media.api-sports.io/football/teams/${name.replace(/\s+/g, '').toLowerCase()}.png`;
};
